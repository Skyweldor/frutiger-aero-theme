// Rebuilds both wallpaper embed stylesheets from assets/*.jpg.
// VS Code's window can't load file:/// images, so wallpapers are inlined as data URIs.
// Run with: npm run build:embed

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const assets = path.join(root, 'assets');
const cssDir = path.join(root, 'css');

// Used until assets/frutiger-aero-night-wallpaper.jpg is added: a CSS-only
// moonlit sky with a soft hill, so the Night mode works out of the box.
const NIGHT_FALLBACK =
  'radial-gradient(circle at 78% 20%, rgba(215, 245, 255, 0.9) 0 2%, rgba(130, 205, 240, 0.25) 6%, transparent 22%), ' +
  'radial-gradient(ellipse at 20% 88%, rgba(12, 72, 76, 0.9) 0%, transparent 55%), ' +
  'linear-gradient(180deg, #020916 0%, #071c33 42%, #0d3551 72%, #12465f 100%)';

/**
 * @param {{image: string, out: string, source: string, note?: string, fallback?: string}} options
 */
function writeEmbed({ image, out, source, note = '', fallback }) {
  const file = path.join(assets, image);
  let value;
  if (fs.existsSync(file)) {
    value = `url("data:image/jpeg;base64,${fs.readFileSync(file).toString('base64')}")`;
  } else if (fallback) {
    value = fallback;
  } else {
    throw new Error(`Missing wallpaper: ${file}`);
  }

  const css =
    '/* Auto-generated by scripts/build-wallpaper-embed.js. Do not edit by hand.\n' +
    `   Embeds ${source} as a data URI, because VS Code\n` +
    '   (vscode-file:// origin) blocks file:/// images.' +
    (note ? `\n   ${note}` : '') +
    ' */\n' +
    `:root { --aero-wallpaper-url: ${value} !important; }\n`;

  fs.writeFileSync(path.join(cssDir, out), css);
  const usingFallback = Boolean(fallback) && value === fallback;
  console.log(
    `Wrote css/${out} (${(css.length / 1024).toFixed(0)} KB)` +
      (usingFallback ? ' [CSS fallback — add your JPG to replace it]' : '')
  );
}

writeEmbed({
  image: 'frutiger-aero-wallpaper.jpg',
  out: 'frutiger-aero-wallpaper-embed.css',
  source: 'assets/frutiger-aero-wallpaper.jpg',
  note: 'Load AFTER frutiger-aero-full-wallpaper.css.',
});

writeEmbed({
  image: 'frutiger-aero-night-wallpaper.jpg',
  out: 'frutiger-aero-night-wallpaper-embed.css',
  source: 'assets/frutiger-aero-night-wallpaper.jpg',
  note: 'Load AFTER frutiger-aero-full-wallpaper.css and frutiger-aero-night-overrides.css.',
  fallback: NIGHT_FALLBACK,
});
